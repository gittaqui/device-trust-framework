"""Render a checked IEEE LaTeX table from frozen synthetic paired-mask JSON.

No model is fitted and no field effectiveness is estimated by this script.
Run from repository root; use --check to verify the committed artifact.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STRATEGIES = ("renormalize", "neutral", "pessimistic", "step_up")
FIELDS = (("false_allow", "unsafe_rows"), ("safe_step_up", "safe_rows"),
          ("false_deny", "safe_rows"))
SOURCES = (("mcar", "MCAR", "paired_missing_telemetry_mcar.json"),
           ("critical_signal_biased", "Critical-biased", "paired_missing_telemetry_critical_signal_biased.json"))


def checked_json(path: Path, expected_model: str) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))
    if data.get("evidence_type") != "synthetic-only" or data.get("mask_model") != expected_model:
        raise ValueError(f"Unexpected evidence category or missingness model: {path}")
    n = data.get("input_rows")
    safe, unsafe = data.get("safe_rows"), data.get("unsafe_rows")
    if not all(type(x) is int and x > 0 for x in (n, safe, unsafe)) or safe + unsafe != n:
        raise ValueError("Invalid row counts")
    if data.get("nominal_missing_rate") != 0.25 or data.get("seed") != 20260904:
        raise ValueError("Unexpected experimental settings")
    if not isinstance(data.get("observed_missing_fraction"), (float, int)) or not 0 <= data["observed_missing_fraction"] <= 1:
        raise ValueError("Invalid realized missingness")
    strategies = data.get("strategies", {})
    if set(strategies) != set(STRATEGIES) | {"confidence"}:
        raise ValueError("Unexpected strategy set")
    for name, values in strategies.items():
        decisions = values.get("decision_counts", {})
        if sum(decisions.get(d, 0) for d in ("ALLOW", "STEP_UP", "DENY")) != n:
            raise ValueError(f"Invalid decision totals: {name}")
        for field, denominator_key in FIELDS:
            count = values.get(f"{field}_count")
            rate = values.get(f"{field}_rate")
            denominator = data[denominator_key]
            if type(count) is not int or not 0 <= count <= denominator:
                raise ValueError(f"Invalid {field} count: {name}")
            if not isinstance(rate, (int, float)) or not math.isfinite(rate) or not math.isclose(rate, count / denominator, rel_tol=0, abs_tol=1e-12):
                raise ValueError(f"Invalid {field} rate: {name}")
    # An algebraically duplicate strategy must not be presented as independent evidence.
    for field, _ in FIELDS:
        if strategies["confidence"][f"{field}_count"] != strategies["pessimistic"][f"{field}_count"]:
            raise ValueError("Confidence and pessimistic policies diverged")
    if strategies["confidence"]["decision_counts"] != strategies["pessimistic"]["decision_counts"]:
        raise ValueError("Confidence and pessimistic decision totals diverged")
    return data


def render(data_dir: Path) -> str:
    datasets = [(label, checked_json(data_dir / filename, key)) for key, label, filename in SOURCES]
    first = datasets[0][1]
    if any((d["input_rows"], d["safe_rows"], d["unsafe_rows"], d["scenario_counts"]) !=
           (first["input_rows"], first["safe_rows"], first["unsafe_rows"], first["scenario_counts"])
           for _, d in datasets[1:]):
        raise ValueError("Regimes must share the same synthetic source population")
    lines = [
        "% AUTO-GENERATED by scripts/render_paired_missingness_table.py; do not edit.",
        "% Synthetic experiment only; no field-effectiveness estimates.",
        "\\begin{table*}[t]", "\\centering", "\\small",
        "\\caption{Paired-mask synthetic missing-telemetry comparison (50,000 rows; 25\\% nominal missingness).}",
        "\\label{tab:paired-missingness}",
        "\\begin{tabular}{llrrr}", "\\toprule",
        "Mask & Policy & Unsafe ALLOW & Safe STEP\\_UP & Safe DENY " + "\\" * 2,
        "\\midrule",
    ]
    labels = {"renormalize": "Renormalize", "neutral": "Neutral", "pessimistic": "Pessimistic", "step_up": "Explicit step-up"}
    for i, (mask_label, data) in enumerate(datasets):
        if i:
            lines.append("\\midrule")
        for strategy in STRATEGIES:
            values = data["strategies"][strategy]
            rates = [100 * values[f"{field}_count"] / data[denom] for field, denom in FIELDS]
            lines.append(f"{mask_label} & {labels[strategy]} & {rates[0]:.2f}\\% & {rates[1]:.2f}\\% & {rates[2]:.2f}\\% " + "\\" * 2)
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    return "\n".join(lines)



def render_operational(data_dir: Path) -> str:
    """Render fixed-policy access coverage with audited label denominators."""
    datasets = [(label, checked_json(data_dir / filename, key)) for key, label, filename in SOURCES]
    first = datasets[0][1]
    if any((d["input_rows"], d["safe_rows"], d["unsafe_rows"], d["scenario_counts"]) !=
           (first["input_rows"], first["safe_rows"], first["unsafe_rows"], first["scenario_counts"])
           for _, d in datasets[1:]):
        raise ValueError("Regimes must share the same synthetic source population")
    lines = [
        "% AUTO-GENERATED by scripts/audit_missingness_operational_coverage.py.",
        "% Frozen paired-mask synthetic observations only; no production claim.",
        "\\begin{table*}[t]", "\\centering", "\\small",
        "\\caption{Operational coverage of fixed missing-telemetry policies on 50,000 synthetic observations (25\\% nominal missingness).}",
        "\\label{tab:missingness-operational-coverage}",
        "\\begin{tabular}{llrrr}", "\\toprule",
        "Mask & Policy & ALLOW/all & Unsafe/ALLOW & Safe friction/safe " + "\\" * 2,
        "\\midrule",
    ]
    labels = {"renormalize": "Renormalize", "neutral": "Neutral", "pessimistic": "Pessimistic", "step_up": "Explicit step-up"}
    for i, (mask_label, data) in enumerate(datasets):
        if i:
            lines.append("\\midrule")
        n, safe = data["input_rows"], data["safe_rows"]
        for strategy in STRATEGIES:
            values = data["strategies"][strategy]
            decisions = values["decision_counts"]
            allow, step, deny = (decisions[k] for k in ("ALLOW", "STEP_UP", "DENY"))
            sa = values["safe_allow_count"]
            ss = values["safe_step_up_count"]
            sd = values["false_deny_count"]
            ua = values["false_allow_count"]
            if any(type(v) is not int or v < 0 for v in (allow, step, deny, sa, ss, sd, ua)):
                raise ValueError("Invalid operational counts")
            if sa + ss + sd != safe or sa + ua != allow or ss > step or sd > deny:
                raise ValueError("Inconsistent label-conditioned operational counts")
            if not math.isclose(values["safe_allow_rate"], sa / safe, abs_tol=1e-12, rel_tol=0):
                raise ValueError("Inconsistent safe-ALLOW rate")
            conditional = f"{100 * ua / allow:.2f}\\%" if allow else "N/A"
            lines.append(f"{mask_label} & {labels[strategy]} & {100 * allow / n:.2f}\\% & {conditional} & {100 * (ss + sd) / safe:.2f}\\% " + "\\" * 2)
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data-dir", type=Path, default=ROOT / "results")
    parser.add_argument("--output", type=Path, default=ROOT / "paper" / "paired-missingness-table.tex")
    parser.add_argument("--check", action="store_true", help="Fail if output differs from regenerated evidence")
    parser.add_argument("--operational", action="store_true", help="Render operational-coverage table")
    args = parser.parse_args()
    content = render_operational(args.data_dir) if args.operational else render(args.data_dir)
    if args.operational and args.output == ROOT / "paper" / "paired-missingness-table.tex":
        args.output = ROOT / "paper" / "missingness-operational-coverage.tex"
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != content:
            raise SystemExit("Generated table is stale or missing")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
